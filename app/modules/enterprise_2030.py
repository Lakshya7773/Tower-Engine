from typing import Optional


TYPOLOGY_SPECS = {
    "Macro GBT": {"load_kw": 2.0, "default_autonomy_h": 12, "dg_baseline_share": 0.45},
    "Urban RTT/Monopole": {"load_kw": 1.5, "default_autonomy_h": 10, "dg_baseline_share": 0.30},
    "5G Street-Furniture Small Cell": {"load_kw": 0.35, "default_autonomy_h": 8, "dg_baseline_share": 0.15},
    "Industrial Private 5G / Edge Node": {"load_kw": 2.5, "default_autonomy_h": 12, "dg_baseline_share": 0.35},
}

STATUTORY_CATEGORIES = {
    "aviation_buffer": {
        "keywords": ("airport", "aerodrome", "helipad", "runway", "airfield", "aviation"),
        "hold_m": 1500.0,
        "warn_m": 4000.0,
    },
    "railways": {
        "keywords": ("railway", "rail", "train", "station", "metro", "track"),
        "hold_m": 50.0,
        "warn_m": 250.0,
    },
    "highways": {
        "keywords": ("highway", "motorway", "trunk", "expressway", "nh-", "nh "),
        "hold_m": 30.0,
        "warn_m": 150.0,
    },
    "waterbodies": {
        "keywords": ("river", "lake", "pond", "canal", "reservoir", "water", "wetland", "dam"),
        "hold_m": 75.0,
        "warn_m": 250.0,
    },
    "forest_eco_zones": {
        "keywords": ("forest", "sanctuary", "wildlife", "national_park", "protected", "reserve", "eco"),
        "hold_m": 300.0,
        "warn_m": 1000.0,
    },
}


def classify_typology(
    population_1km: Optional[int],
    towers_in_radius: int,
    nearest_power_m: Optional[float],
    nearest_ofc_m: Optional[float],
    exclusions: list[dict],
) -> dict:
    """Classify into one of the four 2030 enterprise asset typologies."""
    pop = population_1km or 0
    tags_blob = " ".join(
        f"{e.get('name', '')} {e.get('other_tags', '')}".lower() for e in exclusions
    )
    industrial_hit = any(
        kw in tags_blob for kw in ("industrial", "sez", "factory", "port", "logistics", "plant", "warehouse")
    )

    if industrial_hit and (nearest_ofc_m is None or nearest_ofc_m <= 3000.0):
        typology = "Industrial Private 5G / Edge Node"
        rationale = "Industrial/logistics corridor indicators with viable fiber/power reach."
    elif pop >= 25000 and towers_in_radius >= 12:
        typology = "5G Street-Furniture Small Cell"
        rationale = f"Dense urban catchment ({pop:,} within 1 km, {towers_in_radius} nearby towers) suited for 5G densification."
    elif pop >= 7000 or towers_in_radius >= 5:
        typology = "Urban RTT/Monopole"
        rationale = f"Semi-urban/urban demand ({pop:,} catchment, {towers_in_radius} nearby towers) suited for RTT/Monopole."
    else:
        typology = "Macro GBT"
        rationale = f"Wide-area coverage catchment ({pop:,} within 1 km) requiring Macro Ground-Based Tower."

    return {
        "asset_typology": typology,
        "rationale": rationale,
    }


def simulate_zero_diesel(
    typology: str,
    solar_pvout_kwh_kwp: Optional[float],
    nearest_power_m: Optional[float],
) -> dict:
    """Size Solar PV (kWp) + LiFePO4 battery bank and compute diesel/CO2 savings."""
    spec = TYPOLOGY_SPECS.get(typology, TYPOLOGY_SPECS["Macro GBT"])
    pvout = solar_pvout_kwh_kwp if (solar_pvout_kwh_kwp and solar_pvout_kwh_kwp > 1.0) else 4.8
    load_kw = spec["load_kw"]
    daily_kwh = load_kw * 24.0

    # Grid weakness increases battery autonomy requirement
    autonomy_hours = spec["default_autonomy_h"]
    if nearest_power_m is None or nearest_power_m > 2500.0:
        autonomy_hours = max(autonomy_hours, 24)

    # Solar PV sizing with 0.78 performance ratio
    solar_pv_kwp = round(daily_kwh / (pvout * 0.78), 2)
    # LiFePO4 sizing with 90% depth of discharge
    battery_kwh = round((load_kw * autonomy_hours) / 0.90, 1)

    # Diesel avoided vs legacy DG-hybrid tower (~0.35 L per kWh generated by DG)
    dg_share = spec["dg_baseline_share"]
    if nearest_power_m is None or nearest_power_m > 3000.0:
        dg_share = min(0.75, dg_share + 0.20)

    annual_diesel_saved_l = round(daily_kwh * dg_share * 365.0 * 0.35, 0)
    co2_offset_tpy = round((annual_diesel_saved_l * 2.68) / 1000.0, 2)

    return {
        "solar_pvout_kwh_kwp_day": round(pvout, 2),
        "site_load_kw": load_kw,
        "recommended_solar_pv_kwp": solar_pv_kwp,
        "lifepo4_battery_autonomy_hours": autonomy_hours,
        "lifepo4_battery_kwh": battery_kwh,
        "annual_diesel_saved_liters": int(annual_diesel_saved_l),
        "co2_offset_tons_per_year": co2_offset_tpy,
        "zero_diesel_ready": True,
    }


def evaluate_statutory_row_gate(exclusions: list[dict]) -> dict:
    """Flag proximity to aviation, railways, highways, waterbodies, and forest/eco zones."""
    gates = {}
    overall = "CLEAR"

    for cat, cfg in STATUTORY_CATEGORIES.items():
        matched = []
        for ex in exclusions:
            blob = f"{ex.get('name', '')} {ex.get('other_tags', '')}".lower()
            if any(kw in blob for kw in cfg["keywords"]):
                matched.append(ex)

        if not matched:
            gates[cat] = {
                "status": "CLEAR",
                "nearest_m": None,
                "feature_name": None,
            }
        else:
            nearest = min(matched, key=lambda x: x["distance_m"])
            d = nearest["distance_m"]
            if d <= cfg["hold_m"]:
                status = "HOLD"
                overall = "HOLD_CLEARANCE_REQUIRED"
            elif d <= cfg["warn_m"]:
                status = "WARNING"
                if overall == "CLEAR":
                    overall = "CONDITIONAL_ROW"
            else:
                status = "CLEAR"

            gates[cat] = {
                "status": status,
                "nearest_m": d,
                "feature_name": nearest.get("name") or "UNNAMED",
            }

    return {
        "overall_gate_status": overall,
        "gates": gates,
    }


def score_beyond_tenancy(
    typology: str,
    population_1km: Optional[int],
    nearest_power_m: Optional[float],
    nearest_ofc_m: Optional[float],
    exclusions: list[dict],
) -> dict:
    """Rate suitability for Micro-Edge Compute shelters and EV Charging co-location."""
    pop = population_1km or 0

    # 1. Micro-Edge Compute Score (0-100)
    edge_score = 30.0
    if nearest_ofc_m is not None:
        if nearest_ofc_m <= 500:
            edge_score += 30
        elif nearest_ofc_m <= 1500:
            edge_score += 20
        elif nearest_ofc_m <= 3000:
            edge_score += 10
    if nearest_power_m is not None and nearest_power_m <= 2000:
        edge_score += 20
    elif nearest_power_m is not None and nearest_power_m <= 5000:
        edge_score += 10
    if pop >= 10000:
        edge_score += 15
    elif pop >= 3000:
        edge_score += 8
    if typology in ("Industrial Private 5G / Edge Node", "Urban RTT/Monopole"):
        edge_score += 5
    edge_score = min(100, int(round(edge_score)))

    # 2. EV Charging Co-location Score (0-100)
    ev_score = 20.0
    if typology in ("Macro GBT", "Industrial Private 5G / Edge Node"):
        ev_score += 20  # Ground footprint available
    elif typology == "Urban RTT/Monopole":
        ev_score += 8
    if nearest_power_m is not None:
        if nearest_power_m <= 1000:
            ev_score += 30
        elif nearest_power_m <= 2500:
            ev_score += 18
        elif nearest_power_m <= 5000:
            ev_score += 8
    tags_blob = " ".join(
        f"{e.get('name', '')} {e.get('other_tags', '')}".lower() for e in exclusions
    )
    if any(kw in tags_blob for kw in ("highway", "motorway", "trunk", "nh-")):
        ev_score += 20
    if pop >= 5000:
        ev_score += 10
    ev_score = min(100, int(round(ev_score)))

    def _tier(s: int) -> str:
        return "HIGH" if s >= 70 else ("MODERATE" if s >= 45 else "LOW")

    return {
        "micro_edge_compute": {
            "score": edge_score,
            "tier": _tier(edge_score),
            "suitable": edge_score >= 60,
        },
        "ev_charging_colocation": {
            "score": ev_score,
            "tier": _tier(ev_score),
            "suitable": ev_score >= 60,
        },
        "composite_beyond_tenancy_score": int(round((edge_score + ev_score) / 2.0)),
    }


def analyze_enterprise_2030(
    population_1km: Optional[int],
    towers_in_radius: int,
    nearest_power_m: Optional[float],
    nearest_ofc_m: Optional[float],
    solar_pvout_kwh_kwp: Optional[float],
    exclusions: list[dict],
) -> dict:
    """Unified 2030 Asset Typology, Zero-Diesel ESG, Statutory RoW & Beyond-Tenancy scorer."""
    typology_info = classify_typology(
        population_1km=population_1km,
        towers_in_radius=towers_in_radius,
        nearest_power_m=nearest_power_m,
        nearest_ofc_m=nearest_ofc_m,
        exclusions=exclusions,
    )
    zero_diesel = simulate_zero_diesel(
        typology=typology_info["asset_typology"],
        solar_pvout_kwh_kwp=solar_pvout_kwh_kwp,
        nearest_power_m=nearest_power_m,
    )
    statutory = evaluate_statutory_row_gate(exclusions)
    beyond_tenancy = score_beyond_tenancy(
        typology=typology_info["asset_typology"],
        population_1km=population_1km,
        nearest_power_m=nearest_power_m,
        nearest_ofc_m=nearest_ofc_m,
        exclusions=exclusions,
    )

    return {
        "typology": typology_info,
        "zero_diesel_esg": zero_diesel,
        "statutory_row_gate": statutory,
        "beyond_tenancy": beyond_tenancy,
    }
